-- Lead Intake Triage: the one table all four workflows share.
-- Taken from pg_dump of the running PostgreSQL 17 database (schema only).
-- Run it once against an empty database before importing the workflows.

CREATE TABLE public.leads (
    id bigint NOT NULL,
    gmail_message_id text,
    received_at timestamp with time zone NOT NULL,
    sender_name text,
    sender_email text NOT NULL,
    subject text,
    raw_body text NOT NULL,
    category text NOT NULL,
    summary text,
    extracted_budget text,
    urgency text,
    needs_human_review smallint DEFAULT 0 NOT NULL,
    confidence_note text,
    processed_at timestamp with time zone NOT NULL,
    review_digest_sent_at timestamp with time zone,
    deadline date,
    CONSTRAINT leads_category_check CHECK ((category = ANY (ARRAY['Automation Inquiry'::text, 'Reporting/Data Inquiry'::text, 'Pricing Question'::text, 'Support/Follow-up'::text, 'Spam/Irrelevant'::text, 'Unclear'::text]))),
    CONSTRAINT leads_needs_human_review_check CHECK ((needs_human_review = ANY (ARRAY[0, 1])))
);

ALTER TABLE public.leads ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.leads_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

-- Dedup layer 2: the same Gmail message can never be stored twice.
ALTER TABLE ONLY public.leads
    ADD CONSTRAINT leads_gmail_message_id_key UNIQUE (gmail_message_id);

ALTER TABLE ONLY public.leads
    ADD CONSTRAINT leads_pkey PRIMARY KEY (id);

-- Weekly report: counts per category over the last 7 days.
CREATE INDEX leads_category_received_idx ON public.leads USING btree (category, received_at DESC);

-- Review digest: only rows that need a human.
CREATE INDEX leads_review_idx ON public.leads USING btree (received_at DESC) WHERE (needs_human_review = 1);
